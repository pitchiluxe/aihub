    lines.push("STRIPE_SECRET_KEY=sk_test_...");
    lines.push("NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=pk_test_...");
    lines.push("STRIPE_WEBHOOK_SECRET=whsec_...");
