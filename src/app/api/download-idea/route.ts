// ─── Utility ──────────────────────────────────────────────────────────────────

function skillName(idea: Idea): string {
  return idea.title
    .split(" ")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("")
    .replace(/[^a-zA-Z0-9]/g, "");
}

