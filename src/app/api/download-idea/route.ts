function apiRoute(idea: Idea): string {
  return `import { NextRequest, NextResponse } from "next/server";
import OpenAI from "openai";

const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });

const SYSTEM_PROMPT = \`You are an AI assistant for ${idea.title}, specialised in ${idea.category}.

${idea.solution}

Analyse the user's input and provide a clear, actionable, specific response.
Be direct, precise, and professional. Use bullet points and structure for clarity.\`;

export async function POST(req: NextRequest) {
  try {
    const { input } = await req.json();
    if (!input?.trim()) return NextResponse.json({ error: "Input required" }, { status: 400 });

    const completion = await openai.chat.completions.create({
      model: "gpt-4o",
      messages: [
        { role: "system", content: SYSTEM_PROMPT },
        { role: "user", content: input },
      ],
      max_tokens: 1024,
    });

    return NextResponse.json({ result: completion.choices[0]?.message?.content ?? "" });
  } catch (err) {
    console.error(err);
    return NextResponse.json({ error: "Processing failed" }, { status: 500 });
  }
}
`;
}

